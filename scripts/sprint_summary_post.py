#!/usr/bin/env python3
"""
sprint_summary_post.py — Build and post sprint summary Confluence page.

Reads:  output/sprint.json  (from fetch_sprint.py)
Posts:  Confluence page under COMMAND_PAGE_PARENT_ID
No Claude — zero AI tokens.
"""

import os
import sys
import json
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from confluence_utils import (
    check_env, create_page, xe, h1, h2, p, hr, strong, em, link, table, ul,
    jira_link, page_url, BASE_URL,
)

# ── Config from environment ───────────────────────────────────────────────────
SPACE              = os.environ.get("SPACE", "apiprogram")
COMMAND_PAGE_PARENT_ID = os.environ.get("COMMAND_PAGE_PARENT_ID", "1112015485")
OUTPUT_DIR         = Path(__file__).parent.parent / "output"
# ─────────────────────────────────────────────────────────────────────────────


def build_page_body(data: dict) -> str:
    """Convert sprint.json data to Confluence storage XHTML."""
    sprint   = xe(data.get("sprint_name", "Unknown Sprint"))
    today    = date.today().isoformat()
    project  = xe(data.get("project", "DCPFS"))
    total    = data.get("total_tickets", 0)

    by_status   = data.get("by_status", {})
    by_assignee = data.get("by_assignee", [])
    by_epic     = data.get("by_epic", [])
    blocked     = data.get("blocked", [])
    completed   = data.get("completed", [])

    done_count  = sum(v for k, v in by_status.items() if k.lower() in {"done", "closed", "deployed"})
    ip_count    = sum(v for k, v in by_status.items() if k.lower() in {"in progress", "ready for review", "in review"})
    todo_count  = by_status.get("To Do", 0)
    blk_count   = by_status.get("Blocked", len(blocked))

    parts = []

    # Title & meta
    parts.append(h1(f"Sprint Summary: {data.get('sprint_name', '')}"))
    parts.append(p(f"{strong('Generated:')} {xe(today)} | {strong('Project:')} {project}"))
    parts.append(hr())

    # At a Glance
    parts.append(h2("At a Glance"))
    glance_rows = [
        [xe("Total tickets"),             xe(str(total))],
        [xe("Done / Closed / Deployed"),  xe(str(done_count))],
        [xe("In Progress"),               xe(str(ip_count))],
        [xe("Ready for Review"),          xe(str(by_status.get("Ready for review", 0)))],
        [xe("To Do"),                     xe(str(todo_count))],
        [xe("Blocked"),                   xe(str(blk_count))],
    ]
    parts.append(table(["Metric", "Count"], glance_rows))
    parts.append(hr())

    # By Team Member
    parts.append(h2("By Team Member"))
    if by_assignee:
        member_rows = [
            [
                xe(m["name"]),
                xe(str(m["total"])),
                xe(str(m["in_progress"])),
                xe(str(m["done"])),
                xe(str(m.get("blocked", 0))),
            ]
            for m in by_assignee
        ]
        parts.append(table(["Member", "Total", "In Progress", "Done", "Blocked"], member_rows))
    else:
        parts.append(p("No assignee data available."))
    parts.append(hr())

    # By Epic
    parts.append(h2("By Epic"))
    if by_epic:
        epic_rows = [
            [
                f"{jira_link(e['epic_key'])} {xe(e['epic_name'])}",
                xe(str(e["total"])),
                xe(str(e["done"])),
                xe(str(e["in_progress"])),
            ]
            for e in by_epic
        ]
        parts.append(table(["Epic", "Total", "Done", "In Progress"], epic_rows))
    else:
        parts.append(p("No epic data available."))
    parts.append(hr())

    # Blocked Tickets
    parts.append(h2("Blocked Tickets"))
    if blocked:
        blk_rows = [
            [jira_link(t["key"]), xe(t["summary"]), xe(t["assignee"])]
            for t in blocked
        ]
        parts.append(table(["Ticket", "Summary", "Assignee"], blk_rows))
    else:
        parts.append(p("No blocked tickets this sprint. ✅"))
    parts.append(hr())

    # Completed This Sprint
    parts.append(h2("Completed This Sprint"))
    if completed:
        items = [
            f"{jira_link(t['key'])} — {xe(t['summary'])} ({xe(t['assignee'])})"
            for t in completed
        ]
        parts.append(ul(items))
    else:
        parts.append(p("No tickets completed yet this sprint."))

    parts.append(hr())
    parts.append(p(f"{em('Generated by PIF Automation — ')}{em('./run_command.sh --command sprint_summary')}"))

    return "\n".join(parts)


def main() -> None:
    check_env()

    data_path = OUTPUT_DIR / "sprint.json"
    if not data_path.exists():
        print(f"ERROR: {data_path} not found. Run fetch_sprint.py first.", file=sys.stderr)
        sys.exit(1)

    with open(data_path, encoding="utf-8") as f:
        data = json.load(f)

    sprint_name = data.get("sprint_name", "Unknown")
    today = date.today().isoformat()

    print(f"→ Building sprint summary page for: {sprint_name}")
    body = build_page_body(data)

    title = f"PIF Sprint Summary — {sprint_name} — {today}"
    print(f"→ Posting to Confluence: {title!r}")

    result = create_page(title, body, SPACE, COMMAND_PAGE_PARENT_ID)
    page_id = result["id"]

    print(f"\n✅ Sprint summary posted.")
    print(f"   Sprint: {sprint_name}")
    print(f"   Page:   {page_url(page_id, SPACE)}")


if __name__ == "__main__":
    main()
