#!/usr/bin/env python3
"""
ticket_quality_post.py — Build and post ticket quality audit Confluence page.

Reads:  output/ticket_quality_suggestions.json  (Claude's output from ticket_quality.md)
Posts:  Confluence page under COMMAND_PAGE_PARENT_ID
"""

import os
import sys
import json
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from confluence_utils import (
    check_env, create_page, xe, h1, h2, h3, p, hr, strong, em, link, table, ul,
    jira_link, page_url, BASE_URL,
)

# ── Config from environment ───────────────────────────────────────────────────
SPACE                  = os.environ.get("SPACE", "apiprogram")
COMMAND_PAGE_PARENT_ID = os.environ.get("COMMAND_PAGE_PARENT_ID", "1112015485")
OUTPUT_DIR             = Path(__file__).parent.parent / "output"
# ─────────────────────────────────────────────────────────────────────────────

CLASSIFICATION_LABELS = {
    "complete":      "✅ Complete",
    "missing_ac":    "⚠️ Missing Acceptance Criteria",
    "missing_desc":  "⚠️ Missing Description",
    "missing_both":  "❌ Missing Both",
}


def group_tickets(tickets: list) -> dict[str, list]:
    grouped: dict[str, list] = {
        "missing_both": [],
        "missing_desc": [],
        "missing_ac":   [],
        "complete":     [],
    }
    for t in tickets:
        cls = t.get("classification", "complete")
        grouped.setdefault(cls, []).append(t)
    return grouped


def render_ticket_section(cls: str, tickets: list) -> str:
    """Render one classification section for the page."""
    if not tickets:
        return ""

    label = CLASSIFICATION_LABELS.get(cls, cls)
    parts = [h3(label)]

    # Summary table
    rows = [
        [
            jira_link(t["key"]),
            xe(t.get("summary", "")[:80]),
            xe(t.get("assignee", "")),
            xe(t.get("status", "")),
        ]
        for t in tickets
    ]
    parts.append(table(["Ticket", "Summary", "Assignee", "Status"], rows))

    # Per-ticket suggestions
    for t in tickets:
        key  = t["key"]
        desc = t.get("suggested_description", "")
        ac   = t.get("suggested_ac", [])

        if desc:
            parts.append(p(f"{strong(f'Suggested description for {key}:')}"))
            parts.append(p(f"<em>{xe(desc)}</em>"))

        if ac:
            parts.append(p(f"{strong(f'Suggested acceptance criteria for {key}:')}"))
            ac_items = [f"☐ {xe(a)}" for a in (ac if isinstance(ac, list) else [ac])]
            parts.append(ul(ac_items))

        parts.append(hr())

    return "\n".join(parts)


def build_page_body(data: dict) -> str:
    today       = date.today().isoformat()
    scope       = xe(data.get("scope", "sprint"))
    sprint      = xe(data.get("sprint", ""))
    total       = data.get("total_tickets", 0)
    complete_n  = data.get("complete", 0)
    needs_n     = data.get("needs_attention", 0)

    tickets = data.get("tickets", [])
    grouped = group_tickets(tickets)

    parts = []
    parts.append(h1("PIF Ticket Quality Report"))
    parts.append(p(
        f"{strong('Date:')} {xe(today)} | "
        f"{strong('Scope:')} {scope} | "
        f"{strong('Sprint:')} {sprint}"
    ))
    parts.append(hr())

    # Summary
    parts.append(h2("Summary"))
    parts.append(ul([
        f"✅ {strong(str(complete_n) + ' tickets')} have complete description + acceptance criteria",
        f"⚠️ {strong(str(needs_n) + ' tickets')} need attention (see below)",
    ]))
    parts.append(hr())

    # Needs attention sections
    parts.append(h2("Tickets Needing Attention"))
    if needs_n == 0:
        parts.append(p("All tickets have complete description and acceptance criteria. Great work! ✅"))
    else:
        for cls in ("missing_both", "missing_desc", "missing_ac"):
            section = render_ticket_section(cls, grouped.get(cls, []))
            if section:
                parts.append(section)

    parts.append(hr())
    parts.append(p(f"{em('This report is read-only. Review suggestions above and copy into Jira if approved.')}"))
    parts.append(p(f"{em('Generated by PIF Automation — ./run_command.sh --command ticket_quality')}"))

    return "\n".join(parts)


def main() -> None:
    check_env()

    data_path = OUTPUT_DIR / "ticket_quality_suggestions.json"
    if not data_path.exists():
        print(f"ERROR: {data_path} not found. Run Claude ticket_quality.md first.", file=sys.stderr)
        sys.exit(1)

    with open(data_path, encoding="utf-8") as f:
        data = json.load(f)

    today = date.today().isoformat()

    print(f"→ Building ticket quality report ({data.get('total_tickets', 0)} tickets evaluated)")
    body = build_page_body(data)

    title = f"PIF Ticket Quality Report — {today}"
    print(f"→ Posting to Confluence: {title!r}")

    result = create_page(title, body, SPACE, COMMAND_PAGE_PARENT_ID)
    page_id = result["id"]

    print(f"\n✅ Ticket quality report posted.")
    print(f"   Complete: {data.get('complete', 0)} | Needs attention: {data.get('needs_attention', 0)}")
    print(f"   Page: {page_url(page_id, SPACE)}")


if __name__ == "__main__":
    main()
